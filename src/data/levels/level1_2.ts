import type { Level, Lesson } from '../../types/curriculum';

export type RawLesson = [
  title: string,
  sciencePrinciple: string,
  researcherCitation: string,
  briefing: string,
  conceptQuestion: string,
  conceptOptions: [string, string, string],
  conceptCorrect: 0 | 1 | 2,
  conceptExplanation: string,
  scenarioQuestion: string,
  scenarioOptions: [string, string, string],
  scenarioCorrect: 0 | 1 | 2,
  scenarioExplanation: string,
  speakingPrompt: string,
  targetCues: [string, string, string],
  modelExample: string
];

export function hydrateLessons(levelId: number, rows: RawLesson[]): Lesson[] {
  return rows.map((r, idx) => ({
    id: `L${levelId}-${String(idx + 1).padStart(2, '0')}`,
    levelId,
    order: idx + 1,
    title: r[0],
    sciencePrinciple: r[1],
    researcherCitation: r[2],
    briefing: r[3],
    conceptCheck: {
      question: r[4],
      options: r[5],
      correctIndex: r[6],
      explanation: r[7],
    },
    scenarioCheck: {
      question: r[8],
      options: r[9],
      correctIndex: r[10],
      explanation: r[11],
    },
    speakingPrompt: r[12],
    targetCues: r[13],
    modelExample: r[14],
    xpReward: idx % 5 === 4 ? 35 : 20,
  }));
}

